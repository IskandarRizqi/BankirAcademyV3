<ol>
<li>Jadwal menggunakan zona waktu yang disebutkan; apabila tidak disebutkan, digunakan Waktu Indonesia Barat (WIB).</li>
<li>Bankir Academy dapat mengganti instruktur, lokasi, platform, urutan materi, atau jadwal karena alasan operasional, keselamatan, keadaan darurat, atau kualitas pembelajaran.</li>
<li>Perubahan material akan diinformasikan melalui akun, situs, WhatsApp, email, atau kanal lain yang diberikan Peserta.</li>
<li>Masa akses materi mengikuti masing-masing program. Setelah masa akses berakhir, Bankir Academy dapat menutup akses tanpa kewajiban memberikan salinan.</li>
<li>Peserta bertanggung jawab menyediakan perangkat, koneksi internet, perangkat lunak, dan lingkungan belajar yang memadai.</li>
<li>Rekaman kegiatan hanya tersedia apabila dinyatakan secara tegas pada deskripsi program.</li>
</ol>
</section>
