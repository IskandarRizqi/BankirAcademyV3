<section class="legal-article" id="pendahuluan">
<h2><span class="article-no">01</span>Pendahuluan</h2>
<p>
            Syarat dan Ketentuan ini merupakan perjanjian antara Pengguna dan
            <strong>Bankir Academy</strong> mengenai akses serta penggunaan situs
            <strong>bankiracademy.co.id</strong>, aplikasi atau sistem terkait, kelas daring,
            webinar, pelatihan tatap muka, in-house training, e-book, video pembelajaran,
            konsultasi, sertifikasi, program keanggotaan, dan layanan lain yang tersedia.
          </p>
<p>
            Apabila Pengguna tidak menyetujui sebagian atau seluruh ketentuan ini,
            Pengguna diminta untuk tidak menggunakan Layanan.
          </p>
</section>
<section class="legal-article" id="definisi">
<h2><span class="article-no">02</span>Definisi</h2>
<ol>
<li><strong>Bankir Academy</strong> adalah pengelola situs dan penyedia Layanan.</li>
<li><strong>Situs</strong> adalah bankiracademy.co.id beserta subdomain atau halaman terkait.</li>
<li><strong>Layanan</strong> adalah seluruh program, fitur, konten, produk digital, dan kegiatan yang disediakan.</li>
<li><strong>Pengguna</strong> adalah setiap orang atau badan yang mengakses atau menggunakan Layanan.</li>
<li><strong>Peserta</strong> adalah Pengguna yang terdaftar pada program tertentu.</li>
<li><strong>Instruktur/Mentor</strong> adalah pihak yang memberikan materi, pelatihan, konsultasi, atau pendampingan.</li>
<li><strong>Konten</strong> adalah teks, video, audio, gambar, modul, soal, rekaman, dokumen, dan materi lain dalam Layanan.</li>
<li><strong>Hari Kerja</strong> adalah Senin–Jumat, selain hari libur nasional di Indonesia.</li>
</ol>
</section>
<section class="legal-article" id="persetujuan">
<h2><span class="article-no">03</span>Persetujuan dan Kecakapan Pengguna</h2>
<ol>
<li>Pengguna menyatakan memiliki kecakapan hukum untuk menyetujui perjanjian ini.</li>
<li>Pengguna yang belum berusia 18 tahun wajib memperoleh persetujuan orang tua atau wali yang sah.</li>
<li>Pengguna yang mewakili badan usaha atau instansi menyatakan memiliki kewenangan yang cukup untuk mengikat badan tersebut.</li>
<li>Persetujuan elektronik, termasuk mencentang kotak persetujuan atau melanjutkan transaksi, dianggap sebagai persetujuan yang sah sepanjang diperbolehkan hukum.</li>
</ol>
</section>
<section class="legal-article" id="akun">
<h2><span class="article-no">04</span>Akun, Informasi Pengguna, dan Keamanan</h2>
<ol>
<li>Pengguna wajib memberikan data yang benar, mutakhir, lengkap, dan tidak menyesatkan.</li>
<li>Setiap akun bersifat pribadi dan tidak boleh dipindahtangankan, dijual, disewakan, atau digunakan bersama tanpa izin tertulis.</li>
<li>Pengguna bertanggung jawab menjaga kerahasiaan kata sandi, kode OTP, dan akses akun.</li>
<li>Setiap aktivitas melalui akun dianggap dilakukan oleh pemilik akun, kecuali Pengguna telah segera melaporkan penyalahgunaan.</li>
<li>Bankir Academy dapat meminta verifikasi identitas untuk mencegah penipuan, memastikan penerbitan sertifikat, atau memenuhi kewajiban hukum.</li>
</ol>
</section>
<section class="legal-article" id="layanan">
<h2><span class="article-no">05</span>Ruang Lingkup Layanan</h2>
<p>Layanan Bankir Academy dapat meliputi:</p>
<ul>
<li>kelas mandiri, kelas langsung, webinar, seminar, workshop, dan in-house training;</li>
<li>e-book, modul, video interaktif, kuis, asesmen, dan materi pendukung;</li>
<li>program persiapan karier, konsultasi, lowongan kerja, mentoring, dan keanggotaan;</li>
<li>layanan bagi institusi, sekolah, perguruan tinggi, bank, BPR/BPRS, UMKM, dan organisasi lain;</li>
<li>sertifikat keikutsertaan, penyelesaian, atau kompetensi sesuai ketentuan masing-masing program.</li>
</ul>
<p>
            Deskripsi, jadwal, narasumber, fasilitas, prasyarat, harga, masa akses,
            dan keluaran setiap program mengikuti informasi pada halaman program atau
            dokumen penawaran yang berlaku.
          </p>
</section>
<section class="legal-article" id="pendaftaran">
<h2><span class="article-no">06</span>Pendaftaran dan Keikutsertaan Program</h2>
<ol>
<li>Pendaftaran dinyatakan berhasil setelah data yang dipersyaratkan diterima dan, untuk program berbayar, pembayaran telah terverifikasi.</li>
<li>Kuota dapat dibatasi. Penyelesaian formulir tanpa verifikasi pembayaran tidak selalu menjamin tempat.</li>
<li>Peserta wajib memenuhi prasyarat program, mengikuti tata tertib, dan menggunakan nama yang sesuai identitas untuk keperluan sertifikat.</li>
<li>Bankir Academy berhak menolak atau membatalkan pendaftaran yang terindikasi palsu, melanggar hukum, menyalahgunakan promo, atau mengganggu penyelenggaraan program.</li>
<li>Untuk pendaftaran institusi, pihak pendaftar bertanggung jawab memperoleh persetujuan peserta atas pemberian data kepada Bankir Academy.</li>
</ol>
</section>
<section class="legal-article" id="harga">
<h2><span class="article-no">07</span>Harga, Promo, Pajak, dan Pembayaran</h2>
<ol>
<li>Harga yang berlaku adalah harga yang ditampilkan pada saat transaksi atau tercantum dalam penawaran resmi.</li>
<li>Harga dapat berubah sewaktu-waktu dan tidak berlaku surut terhadap transaksi yang telah dikonfirmasi.</li>
<li>Promo, voucher, beasiswa, atau potongan harga memiliki syarat, kuota, dan periode masing-masing serta tidak selalu dapat digabungkan.</li>
<li>Pengguna wajib membayar melalui metode resmi yang disediakan. Biaya administrasi pihak ketiga dapat dibebankan sesuai informasi saat pembayaran.</li>
<li>Kewajiban pajak mengikuti ketentuan perpajakan yang berlaku dan dapat dicantumkan terpisah bila relevan.</li>
<li>Bankir Academy tidak bertanggung jawab atas pembayaran yang dikirim ke rekening, tautan, atau pihak yang tidak diumumkan melalui kanal resmi.</li>
</ol>
</section>
<section class="legal-article" id="pembatalan">
<h2><span class="article-no">08</span>Pembatalan, Penjadwalan Ulang, dan Pengembalian Dana</h2>
<ol>
<li>
              Permintaan pembatalan oleh Peserta harus disampaikan tertulis melalui kanal resmi
              dengan mencantumkan bukti transaksi dan alasan pembatalan.
            </li>
<li>
              Kecuali disebutkan lain pada halaman program, produk digital yang telah diakses,
              diunduh, atau dikirimkan tidak dapat dikembalikan.
            </li>
<li>
              Untuk kelas terjadwal, permintaan pengembalian dana yang diterima paling lambat
              3 Hari Kerja sebelum pelaksanaan dapat dipertimbangkan setelah dikurangi biaya
              administrasi dan biaya pihak ketiga yang tidak dapat dikembalikan.
            </li>
<li>
              Permintaan yang diterima kurang dari 3 Hari Kerja sebelum pelaksanaan, ketidakhadiran,
              keterlambatan, atau kegagalan Peserta memenuhi persyaratan pada umumnya tidak
              menimbulkan hak pengembalian dana, kecuali ditentukan lain.
            </li>
<li>
              Peserta dapat mengajukan pengalihan jadwal atau penggantian nama peserta sebelum
              batas waktu yang ditetapkan, sepanjang disetujui Bankir Academy.
            </li>
<li>
              Apabila Bankir Academy membatalkan program dan tidak menyediakan jadwal pengganti
              yang disetujui Peserta, pembayaran program akan dikembalikan sesuai nilai yang
              diterima Bankir Academy.
            </li>
<li>
              Proses pengembalian dana dilakukan ke sumber pembayaran atau rekening yang
              terverifikasi dalam jangka waktu operasional yang wajar.
            </li>
</ol>
<div class="highlight-box">
<strong>Catatan implementasi:</strong> Sesuaikan batas waktu pembatalan dan
            biaya administrasi di atas dengan kebijakan operasional Bankir Academy sebelum dipublikasikan.
          </div>
</section>
