<ol>
<li>Sertifikat diberikan berdasarkan jenis program dan pemenuhan persyaratan seperti kehadiran, penyelesaian materi, tugas, asesmen, atau pembayaran.</li>
<li>Sertifikat Bankir Academy tidak otomatis merupakan lisensi profesi, gelar akademik, atau jaminan pengakuan oleh regulator, perusahaan, maupun lembaga lain.</li>
<li>Kesalahan nama yang berasal dari data Peserta dapat dikenakan biaya penerbitan ulang.</li>
<li>Bankir Academy berhak membatalkan sertifikat yang diperoleh melalui kecurangan, pemalsuan, perjokian, atau pelanggaran ketentuan.</li>
</ol>
</section>
